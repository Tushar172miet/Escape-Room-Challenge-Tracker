# Q2 - Multiple Session Management

room_limits = {
    "Lost Laboratory": 60,
    "Ancient Vault": 50,
    "Space Station": 45
}

sessions = []
unique_rooms = set()

fast_count = 0
escaped_count = 0
exceeded_count = 0

while True:
    team = input("\nEnter team name (DONE to stop): ").strip().title()

    if team == "Done":
        break

    room = input("Enter room theme: ").strip().title()

    if room not in room_limits:
        print("Invalid room theme!")
        continue

    try:
        players = int(input("Enter number of players: "))
        raw_time = float(input("Enter raw completion time: "))
        hints = int(input("Enter hints used: "))
    except ValueError:
        print("Please enter valid numbers!")
        continue

    if players < 2 or players > 6:
        print("Players must be between 2 and 6.")
        continue

    if raw_time <= 0 or hints < 0:
        print("Invalid time or hints!")
        continue

    penalty = hints * 3
    adjusted_time = raw_time + penalty
    limit = room_limits[room]

    if adjusted_time <= 0.70 * limit:
        outcome = "FAST ESCAPE"
        fast_count += 1
    elif adjusted_time <= limit:
        outcome = "ESCAPED"
        escaped_count += 1
    else:
        outcome = "TIME EXCEEDED"
        exceeded_count += 1

    record = {
        "team": team,
        "room": room,
        "players": players,
        "adjusted_time": adjusted_time,
        "outcome": outcome
    }

    sessions.append(record)
    unique_rooms.add(room)

    print("\nOutcome:", outcome)
    print("Adjusted Time:", adjusted_time)

print("\n===== FINAL SESSION REPORT =====")
print("Total Sessions:", len(sessions))
print("Fast Escapes:", fast_count)
print("Escaped:", escaped_count)
print("Time Exceeded:", exceeded_count)
print("Unique Rooms:", unique_rooms)

if sessions:
    best = min(sessions, key=lambda x: x["adjusted_time"])
    print("Best Team:", best["team"])
    print("Best Time:", best["adjusted_time"])

