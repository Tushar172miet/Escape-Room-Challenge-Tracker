# Q3 - Object-Oriented Programming

class EscapeSession:

    venue_name = "Mystery Escape Arena"

    def __init__(self, session_id, team_name, room_theme,
                 players, raw_time, hints_used, room_limit):

        self.session_id = session_id
        self.team_name = team_name
        self.room_theme = room_theme
        self.players = players
        self.raw_time = raw_time
        self.hints_used = hints_used
        self.room_limit = room_limit

    def adjusted_time(self):
        return self.raw_time + (self.hints_used * 3)

    def outcome(self):
        time = self.adjusted_time()

        if time <= 0.70 * self.room_limit:
            return "FAST ESCAPE"
        elif time <= self.room_limit:
            return "ESCAPED"
        else:
            return "TIME EXCEEDED"

    def display_summary(self):
        print("\nSession ID:", self.session_id)
        print("Team:", self.team_name)
        print("Room:", self.room_theme)
        print("Players:", self.players)
        print("Adjusted Time:", self.adjusted_time())
        print("Outcome:", self.outcome())
        print("Venue:", self.venue_name)

    def __str__(self):
        return (self.team_name + " - " +
                self.room_theme + " - " + self.outcome())

